const require = createRequire(import.meta.url)
const mobileRoot = path.resolve(import.meta.dirname, '..')
const reactSource = require.resolve('react')
const sourceMap = {
  version: 3,
  sources: [reactSource, '/does-not-exist-but-is-not-emitted.js'],
  sourcesContent: [fs.readFileSync(reactSource, 'utf8'), null],
  mappings: 'AAAA'
}

test('Metro inventory includes mapped sources only and records references instead of bytes', () => {
  const graph = metroNoticeProvenance(sourceMap, mobileRoot)
  assert.equal(graph.sources.length, 1)
  assert.equal(graph.mappingReferences, 1)
  assert.deepEqual(graph.metafile.outputs['main.jsbundle'].inputs[reactSource], {
    mappingReferences: 1
  })
  assert.equal(graph.metafile.x_provenance.lengthUnit, 'source-map references')
})

test('Metro inventory rejects missing mapped sources and invalid source indices', () => {
  assert.throws(
    () => metroNoticeProvenance({ ...sourceMap, mappings: 'ACAA' }, mobileRoot),
    /ENOENT|not a file/
  )
  assert.throws(
    () => metroNoticeProvenance({ ...sourceMap, mappings: 'AEAA' }, mobileRoot),
    /missing source/
  )
})

test('Metro refuses a generated input that changed after bundling', () => {
  const generated = path.join(mobileRoot, 'src/terminal/terminal-webview-engine.generated.ts')
  assert.throws(
    () =>
      metroNoticeProvenance(
        {
          version: 3,
          sources: [generated],
          sourcesContent: ['stale generated bytes'],
          mappings: 'AAAA'
        },
        mobileRoot
      ),
    /changed since Metro/
  )
})

test('Hermes-normalized paths require an unambiguous full-path content match inside the checkout', () => {
  const repository = fs.mkdtempSync(path.join(os.tmpdir(), 'ab-ios-map-paths-test-'))
  const project = path.join(repository, 'mobile')
  const relative = 'src/shared/source.ts'
  const rootFile = path.join(repository, relative)
  const mobileFile = path.join(project, relative)
  const content = 'export const archiveSource = true\n'
  try {
    for (const file of [rootFile, mobileFile]) {
      fs.mkdirSync(path.dirname(file), { recursive: true })
    }
    fs.writeFileSync(rootFile, content)
    fs.writeFileSync(mobileFile, 'different mobile module\n')
    const map = {
      version: 3,
      sources: [`/${relative}`],
      sourcesContent: [content],
      mappings: 'AAAA'
    }
    const selected = metroNoticeProvenance(map, project).sources[0]
    assert.equal(selected.path, relative)
    assert.equal(selected.contentVerification, 'sha256-match')
    assert.deepEqual(selected.sourceMapSources, [`/${relative}`])
    assert.throws(
      () => metroNoticeProvenance({ ...map, sourcesContent: [null] }, project),
      /lacks content/
    )
    fs.writeFileSync(mobileFile, content)
    assert.throws(() => metroNoticeProvenance(map, project), /ambiguous checkout paths/)
    fs.unlinkSync(rootFile)
    fs.symlinkSync(import.meta.filename, rootFile)
    fs.unlinkSync(mobileFile)
    assert.throws(() => metroNoticeProvenance(map, project), /outside the repository/)
  } finally {
    fs.rmSync(repository, { recursive: true, force: true })
  }
})

test('contentless PNG references require one full-path candidate and explicitly limit verification', () => {
  const repository = fs.mkdtempSync(path.join(os.tmpdir(), 'ab-ios-map-assets-test-'))
  const project = path.join(repository, 'mobile')
  const relative = 'assets/icon.png'
  const rootFile = path.join(repository, relative)
  const mobileFile = path.join(project, relative)
  try {
    fs.mkdirSync(path.dirname(rootFile), { recursive: true })
    fs.mkdirSync(path.dirname(mobileFile), { recursive: true })
    fs.writeFileSync(rootFile, Buffer.from([137, 80, 78, 71]))
    const map = { version: 3, sources: [`/${relative}`], sourcesContent: [''], mappings: 'AAAA' }
    const selected = metroNoticeProvenance(map, project).sources[0]
    assert.equal(selected.path, relative)
    assert.equal(selected.contentVerification, 'not-in-source-map')
    assert.match(selected.sha256, /^[a-f0-9]{64}$/)
    fs.copyFileSync(rootFile, mobileFile)
    assert.throws(() => metroNoticeProvenance(map, project), /ambiguous/)
  } finally {
    fs.rmSync(repository, { recursive: true, force: true })
  }
})

test('notice phase follows bundling and resource copies exactly once', () => {
  const project = {
    hash: {
      project: {
        objects: {
          PBXNativeTarget: {
            APP: {
              productType: '"com.apple.product-type.application"',
              buildPhases: [
                { value: 'BUNDLE', comment: 'Bundle React Native code and images' },
                { value: 'RESOURCES', comment: '[CP] Copy Pods Resources' }
              ]
            }
          },
          PBXShellScriptBuildPhase: {
            BUNDLE: {
              name: '"Bundle React Native code and images"',
              shellScript: JSON.stringify('echo "fixture bundle"\n')
            },
            RESOURCES: { name: '"[CP] Copy Pods Resources"' }
          }
        }
      }
    },
    addBuildPhase(_files, _type, name) {
      this.hash.project.objects.PBXShellScriptBuildPhase.NOTICES = { name: JSON.stringify(name) }
      return { uuid: 'NOTICES' }
    }
  }
  configureIosNoticePhase(project)
  const result = configureIosNoticePhase(project)
  assert.deepEqual(result.order, [
    'Bundle React Native code and images',
    '[CP] Copy Pods Resources',
    NOTICE_PHASE
  ])
  const phases = project.hash.project.objects.PBXShellScriptBuildPhase
  assert.equal(JSON.parse(phases.BUNDLE.shellScript).match(/export SOURCEMAP_FILE/g).length, 1)
  assert.match(JSON.parse(phases.NOTICES.shellScript), /ab-ios-notices\.mjs" from-xcode/)
  assert.doesNotMatch(JSON.parse(phases.NOTICES.shellScript), /curl|wget|codesign|security /)
  delete phases.BUNDLE
  assert.throws(() => configureIosNoticePhase(project), /no React Native bundle phase/)
})

function fixture() {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'ab-ios-notices-test-'))
  const appPath = path.join(directory, 'UnsignedFixture.app')
  const podsRoot = path.join(directory, 'Pods')
  const acknowledgements = path.join(
    podsRoot,
    'Target Support Files/Pods-Fixture/Pods-Fixture-acknowledgements'
  )
  fs.mkdirSync(appPath)
  fs.mkdirSync(path.dirname(acknowledgements), { recursive: true })
  fs.writeFileSync(
    path.join(appPath, 'main.jsbundle'),
    'fixture JavaScript — not a compiled iOS application'
  )
  fs.writeFileSync(path.join(directory, 'map.json'), JSON.stringify(sourceMap))
  fs.writeFileSync(path.join(directory, 'Podfile.lock'), 'PODS:\n  - Fixture (1.0)\n')
  fs.copyFileSync(path.join(directory, 'Podfile.lock'), path.join(podsRoot, 'Manifest.lock'))
  fs.writeFileSync(
    `${acknowledgements}.markdown`,
    '# Fixture acknowledgement\nSynthetic native test data.\n'
  )
  fs.writeFileSync(
    `${acknowledgements}.plist`,
    '<?xml version="1.0"?><plist version="1.0"><dict><key>PreferenceSpecifiers</key><array><dict><key>Title</key><string>Fixture</string><key>FooterText</key><string>Synthetic native test acknowledgement.</string></dict></array></dict></plist>'
  )
  return {
    directory,
    appPath,
    sourceMapPath: path.join(directory, 'map.json'),
    podsRoot,
    targetName: 'Fixture',
    receiptPath: path.join(directory, 'receipt.json')
  }
}

test('staged unsigned resources verify, then missing/altered text, bundle and receipt tampering are rejected', async () => {
  const context = fixture()
  try {
    const receipt = await stageIosNotices(context)
    assert.equal(receipt.npmPackages, 1)
    assert.equal(receipt.nativeAcknowledgements, 1)
    assert.equal(
      verifyIosNotices(context.appPath, receipt.manifestSha256).manifestSha256,
      receipt.manifestSha256
    )
    const notices = path.join(context.appPath, NOTICES_DIRECTORY)
    const text = path.join(notices, 'Orca-MIT.txt')
    const original = fs.readFileSync(text)
    fs.unlinkSync(text)
    assert.throws(() => verifyIosNotices(context.appPath), /missing, changed, or unlisted/)
    fs.writeFileSync(text, 'modified licence')
    assert.throws(() => verifyIosNotices(context.appPath), /missing, changed, or unlisted/)
    fs.writeFileSync(text, original)
    fs.appendFileSync(path.join(context.appPath, 'main.jsbundle'), 'tampered')
    assert.throws(() => verifyIosNotices(context.appPath), /JavaScript bundle differs/)
    assert.throws(() => verifyIosNotices(context.appPath, '0'.repeat(64)), /build-phase receipt/)
  } finally {
    fs.rmSync(context.directory, { recursive: true, force: true })
  }
})

test('generation refuses signed applications and unavailable CocoaPods acknowledgement resources', async () => {
  const context = fixture()
  try {
    fs.mkdirSync(path.join(context.appPath, '_CodeSignature'))
    await assert.rejects(stageIosNotices(context), /existing code signature/)
    fs.rmdirSync(path.join(context.appPath, '_CodeSignature'))
    fs.unlinkSync(
      path.join(
        context.podsRoot,
        'Target Support Files/Pods-Fixture/Pods-Fixture-acknowledgements.plist'
      )
    )
    await assert.rejects(stageIosNotices(context), /ENOENT/)
  } finally {
    fs.rmSync(context.directory, { recursive: true, force: true })
  }
})
